<?php
declare(strict_types=1);

namespace LeenTrack\Services;

use LeenTrack\Core\ApiException;
use LeenTrack\Core\Clock;
use LeenTrack\Core\Db;
use LeenTrack\Core\Money;
use LeenTrack\Core\Pager;
use LeenTrack\Core\Request;
use LeenTrack\Core\Uuid;
use LeenTrack\Core\Validator;
use LeenTrack\Http\TenantContext;
use LeenTrack\Repositories\CustomerRepository;
use LeenTrack\Repositories\SaleRepository;
use LeenTrack\Services\Documents\DocumentBuilder;
use PDO;

/**
 * Credit sales: who owes what, recording repayments, statements.
 * Balance of a sale = total − money paid at the till − Σ repayments (never below 0). A sale is "open" while payment_status='pending'.
 * Lock order is the global one: customer → sale. Repayment rows are append-only (no update/delete code path exists).
 */
final class CreditService
{
    public const OVERDUE_DAYS = 30;       // credit/page.tsx: ≥ 30 days old = "Overdue!"
    public const WARN_DAYS = 14;          // ≥ 14 days = "2 weeks"
    private const METHODS = ['cash', 'card', 'bank_transfer', 'mobile_money', 'other'];

    public function __construct(
        private readonly PDO $pdo,
        private readonly SaleRepository $sales,
        private readonly CustomerRepository $customers,
        private readonly LoyaltyService $loyalty,
        private readonly AuditService $audit,
    ) {
    }

    // ================================================================================================ repay
    /**
     * @param array<string,mixed> $body
     * @return array{result:array<string,mixed>,replayed:bool}
     */
    public function repay(TenantContext $t, string $saleId, array $body, ?string $headerKey, Request $req): array
    {
        $t->require('credit.repay');
        if (!Uuid::isValid($saleId)) { throw ApiException::notFound(); }
        $v = new Validator($body);
        $v->only(['amount', 'method', 'notes', 'client_operation_id']);
        $amount = $v->money('amount', true);
        $m = $v->has('method') ? $v->enum('method', array_merge(self::METHODS, ['transfer']), false, 'cash') : 'cash';
        $method = $m === 'transfer' ? 'bank_transfer' : (string) $m;
        $notes = $v->string('notes', 1, 300, false);
        $op = $v->has('client_operation_id') ? $v->uuid('client_operation_id') : null;
        if ($op === null && $headerKey !== null) {
            if (Uuid::isValid($headerKey)) { $op = $headerKey; } else { $v->addError('client_operation_id', 'Idempotency-Key must be a UUID.'); }
        }
        if ($op === null && !$v->has('client_operation_id')) { $v->addError('client_operation_id', 'This field is required (a UUID generated by the device, reused on retry).'); }
        if ($amount !== null && $amount->isZero()) { $v->addError('amount', 'Enter the amount they are paying.'); }
        $v->done();
        $bid = $t->businessId;

        $outcome = null;
        try {
            $outcome = Db::transaction($this->pdo, fn () => $this->repayTx($t, $saleId, $amount, $method, $notes, (string) $op, $req));
        } catch (\PDOException $e) {
            if ((int) ($e->errorInfo[1] ?? 0) === 1062 && str_contains((string) $e->getMessage(), 'uq_repay_operation')) {
                $existing = $this->sales->repaymentByOperation($bid, (string) $op);
                if ($existing !== null) { return ['result' => $this->replayView($t, $existing, $saleId, $amount, $method, $notes), 'replayed' => true]; }
            }
            throw $e;
        }
        return $outcome;
    }

    /** @return array{result:array<string,mixed>,replayed:bool} */
    private function repayTx(TenantContext $t, string $saleId, Money $amount, string $method, ?string $notes, string $opId, Request $req): array
    {
        $bid = $t->businessId;
        $pre = $this->sales->saleCustomerId($bid, $saleId) ?? throw ApiException::notFound('Sale not found.');
        $customerId = $pre['customer_id'];
        if ($customerId === null) { throw new ApiException('not_open', 'This sale has no customer, so nothing is owed on it.', 409); }
        $this->customers->lockCustomer($bid, (string) $customerId);                                   // 1. customer
        $sale = $this->sales->lockSale($bid, $saleId) ?? throw ApiException::notFound('Sale not found.');   // 2. sale
        if ($sale['outlet_id'] !== null && !$t->canAccessOutlet((string) $sale['outlet_id'])) { throw ApiException::notFound('Sale not found.'); }

        // Idempotent replay (decided under the locks, so two racing identical requests cannot both insert)
        $existing = $this->sales->repaymentByOperation($bid, $opId);
        if ($existing !== null) {
            return ['result' => $this->replayView($t, $existing, $saleId, $amount, $method, $notes), 'replayed' => true];
        }
        if ($sale['payment_status'] === 'voided') { throw new ApiException('not_open', 'This sale was voided, so no payment can be recorded on it.', 409); }
        if ($sale['payment_status'] !== 'pending') { throw new ApiException('not_open', 'Nothing is owed on this sale.', 409); }

        $total = Money::parse($sale['total_amount']);
        $upfront = Money::parse($sale['amount_paid']);
        $repaid = Money::parse($this->sales->repaidTotal($bid, $saleId));
        $balance = $total->sub($upfront)->sub($repaid);
        if ($balance->minor < 1) { throw new ApiException('not_open', 'Nothing is owed on this sale.', 409); }
        if ($amount->gt($balance)) {
            throw ApiException::validation(['amount' => ['Amount cannot be more than what they owe (' . $balance->toString() . ').']]);
        }

        $id = Uuid::v4();
        $this->sales->insertRepayment(['id' => $id, 'business_id' => $bid, 'sale_id' => $saleId, 'customer_id' => $customerId, 'amount' => $amount->toString(), 'payment_method' => $method, 'notes' => $notes, 'client_operation_id' => $opId, 'created_by' => $t->userId]);
        $newBalance = $balance->sub($amount);
        $status = 'pending';
        if ($newBalance->minor < 1) {
            $status = 'completed';
            $this->sales->updateSale($bid, $saleId, ['payment_status' => 'completed']);
        }
        $this->customers->adjustStats($bid, (string) $customerId, $amount->toString(), 0, null);      // money received
        $this->loyalty->apply($bid, (string) $customerId, $saleId, $amount, 'Payment on a credit sale', $t->userId);
        $this->audit->log('credit.repay', $req, $t->userId, $bid, 'sale', $saleId, ['balance' => $balance->toString()], ['paid' => $amount->toString(), 'balance' => $newBalance->toString(), 'method' => $method]);

        $created = $this->sales->repayments($bid, [$saleId]);
        $row = array_values(array_filter($created, fn ($r) => $r['id'] === $id))[0];
        return ['result' => $this->resultView($t, $row, $sale, $balance, $newBalance, $status), 'replayed' => false];
    }

    /** @param array<string,mixed> $existing */
    private function replayView(TenantContext $t, array $existing, string $saleId, Money $amount, string $method, ?string $notes): array
    {
        if ($existing['sale_id'] !== $saleId || Money::parse($existing['amount'])->minor !== $amount->minor || $existing['payment_method'] !== $method || ($existing['notes'] ?? null) !== $notes) {
            throw new ApiException('idempotency_conflict', 'This operation id was already used for a different payment.', 409);
        }
        $sale = $this->sales->sale($t->businessId, $saleId) ?? throw ApiException::notFound();
        // Exact reconstruction: balance just before this payment = total − upfront − payments recorded earlier than it.
        $running = Money::parse($sale['total_amount'])->sub(Money::parse($sale['amount_paid']));
        $previous = $running;
        $after = $running;
        foreach ($this->sales->repayments($t->businessId, [$saleId]) as $r) {          // ordered by created_at, id
            if ($r['id'] === $existing['id']) { $previous = $running; $after = $running->sub(Money::parse($r['amount'])); break; }
            $running = $running->sub(Money::parse($r['amount']));
        }
        $previous = $previous->isNegative() ? Money::zero() : $previous;
        $after = $after->isNegative() ? Money::zero() : $after;
        $row = ['id' => $existing['id'], 'sale_id' => $saleId, 'amount' => $existing['amount'], 'payment_method' => $existing['payment_method'], 'notes' => $existing['notes'], 'created_at' => $existing['created_at']];
        return $this->resultView($t, $row, $sale, $previous, $after, $after->minor < 1 ? 'completed' : 'pending');
    }

    /** @param array<string,mixed> $row repayment @param array<string,mixed> $sale */
    private function resultView(TenantContext $t, array $row, array $sale, Money $previous, Money $new, string $status): array
    {
        $cust = $sale['customer_id'] === null ? null : $this->customers->customer($t->businessId, (string) $sale['customer_id'], true);
        $biz = $this->sales->businessInfo($t->businessId) ?? throw ApiException::notFound();
        $symbols = ['NGN' => '₦', 'GHS' => '₵', 'KES' => 'KSh', 'ZAR' => 'R', 'EGP' => 'EGP ', 'USD' => '$', 'GBP' => '£', 'EUR' => '€', 'XOF' => 'CFA'];
        $doc = DocumentBuilder::fromPayment([
            'reference' => (string) $sale['receipt_number'], 'date' => (new \DateTimeImmutable($row['created_at'], new \DateTimeZone('UTC')))->format('Y-m-d\TH:i:s.v\Z'),
            'customer' => ['name' => (string) ($cust['name'] ?? ''), 'phone' => $cust['phone'] ?? null, 'email' => $cust['email'] ?? null],
            'amount' => Money::parse($row['amount']), 'method' => (string) $row['payment_method'], 'previousBalance' => $previous, 'newBalance' => $new,
        ], ['businessName' => (string) $biz['name'], 'branding' => $this->sales->branding($t->businessId), 'currencyCode' => (string) $biz['currency'], 'currencySymbol' => $symbols[$biz['currency']] ?? '']);
        return [
            'repayment' => ['id' => $row['id'], 'sale_id' => $row['sale_id'], 'amount' => $row['amount'], 'payment_method' => $row['payment_method'], 'notes' => $row['notes'], 'created_at' => (new \DateTimeImmutable($row['created_at'], new \DateTimeZone('UTC')))->format('Y-m-d\TH:i:s.v\Z')],
            'sale' => ['id' => $sale['id'], 'receipt_number' => $sale['receipt_number'], 'status' => $status, 'previous_balance' => $previous->toString(), 'balance_due' => $new->toString()],
            'document' => DocumentBuilder::toApi($doc),
        ];
    }

    /** Nested routes under /customers/{id} answer 404 for ids that are not in this business (same as every other resource). */
    public function assertCustomer(TenantContext $t, string $customerId): void
    {
        if (!Uuid::isValid($customerId) || $this->customers->customer($t->businessId, $customerId, true) === null) { throw ApiException::notFound(); }
    }

    // ================================================================================================ list (credit page)
    /** @param array<string,mixed> $q @return array{rows:list<array<string,mixed>>,meta:array<string,mixed>} */
    public function list(TenantContext $t, array $q): array
    {
        $t->require('credit.read');
        $allowed = ['search', 'customer_id', 'overdue', 'page', 'per_page'];
        if ($extra = array_diff(array_keys($q), $allowed)) { throw ApiException::validation([(string) reset($extra) => ['Unknown filter.']]); }
        $customerId = $this->uuid($q, 'customer_id');
        $search = isset($q['search']) ? (is_string($q['search']) && $q['search'] !== '' && mb_strlen($q['search']) <= 100 ? mb_strtolower($q['search']) : throw ApiException::validation(['search' => ['Must be text up to 100 characters.']])) : null;
        $onlyOverdue = false;
        if (isset($q['overdue'])) {
            if (!in_array($q['overdue'], ['0', '1', 'true', 'false'], true)) { throw ApiException::validation(['overdue' => ['Must be true or false.']]); }
            $onlyOverdue = in_array($q['overdue'], ['1', 'true'], true);
        }
        $debts = $this->groupDebts($t, $this->sales->openCredit($t->businessId, $customerId, $t->outletIds));
        if ($search !== null) {
            $debts = array_values(array_filter($debts, fn ($c) => str_contains(mb_strtolower($c['name']), $search) || str_contains((string) $c['phone'], $search)));
        }
        if ($onlyOverdue) { $debts = array_values(array_filter($debts, fn ($c) => $c['is_overdue'])); }
        $sum = $this->sumDebts($debts);
        $pg = Pager::fromQuery($q, 100);
        $page = array_slice($debts, $pg->offset(), $pg->perPage);
        return ['rows' => $page, 'meta' => $pg->meta(count($debts)) + ['summary' => $sum]];
    }

    /**
     * The ONE definition of "how much is owed / overdue", used by the credit page AND the dashboard (the source's dashboard ignored repayments).
     * @param list<string>|null $outletIds
     * @return array{total_owed:string,overdue_owed:string,customers:int,open_sales:int}
     */
    public function totals(TenantContext $t, ?array $outletIds): array
    {
        $t->require('credit.read');
        return $this->sumDebts($this->groupDebts($t, $this->sales->openCredit($t->businessId, null, $outletIds)));
    }

    /** @param list<array<string,mixed>> $debts @return array{total_owed:string,overdue_owed:string,customers:int,open_sales:int} */
    private function sumDebts(array $debts): array
    {
        $totalOwed = Money::zero();
        $overdueOwed = Money::zero();
        $openSales = 0;
        foreach ($debts as $c) {
            $totalOwed = $totalOwed->add(Money::parse($c['total_owed']));
            $openSales += count($c['sales']);
            foreach ($c['sales'] as $s) { if ($s['days_old'] >= self::OVERDUE_DAYS) { $overdueOwed = $overdueOwed->add(Money::parse($s['balance_due'])); } }
        }
        return ['total_owed' => $totalOwed->toString(), 'overdue_owed' => $overdueOwed->toString(), 'customers' => count($debts), 'open_sales' => $openSales];
    }

    /** @return array<string,mixed> */
    public function debt(TenantContext $t, string $customerId): array
    {
        $t->require('credit.read');
        if (!Uuid::isValid($customerId)) { throw ApiException::notFound(); }
        $c = $this->customers->customer($t->businessId, $customerId, true) ?? throw ApiException::notFound();
        $d = $this->groupDebts($t, $this->sales->openCredit($t->businessId, $customerId, $t->outletIds));
        return $d[0] ?? ['id' => $c['id'], 'name' => $c['name'], 'phone' => $c['phone'], 'total_owed' => '0.00', 'oldest_debt_date' => null, 'oldest_days' => 0, 'is_overdue' => false, 'sales' => []];
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>> customers with debts, biggest debt first (as credit/page.tsx)
     */
    private function groupDebts(TenantContext $t, array $rows): array
    {
        $reps = [];
        foreach ($this->sales->repayments($t->businessId, array_column($rows, 'id')) as $r) { $reps[$r['sale_id']][] = ['id' => $r['id'], 'amount' => $r['amount'], 'payment_method' => $r['payment_method'], 'notes' => $r['notes'], 'created_at' => $this->iso($r['created_at'])]; }
        $now = Clock::now()->getTimestamp();
        $by = [];
        foreach ($rows as $r) {
            $bal = Money::parse($r['total_amount'])->sub(Money::parse($r['amount_paid']))->sub(Money::parse($r['repaid']));
            $created = new \DateTimeImmutable($r['created_at'], new \DateTimeZone('UTC'));
            $days = intdiv(max(0, $now - $created->getTimestamp()), 86400);
            $cid = (string) $r['customer_id'];
            $by[$cid] ??= ['id' => $cid, 'name' => (string) $r['customer_name'], 'phone' => $r['customer_phone'], 'owed' => Money::zero(), 'oldest' => $r['created_at'], 'oldest_days' => $days, 'sales' => []];
            $by[$cid]['owed'] = $by[$cid]['owed']->add($bal);
            $by[$cid]['oldest_days'] = max($by[$cid]['oldest_days'], $days);
            $by[$cid]['sales'][] = ['id' => $r['id'], 'receipt_number' => $r['receipt_number'], 'total_amount' => $r['total_amount'], 'amount_paid_upfront' => $r['amount_paid'], 'total_repaid' => Money::parse($r['repaid'])->toString(),
                'balance_due' => $bal->toString(), 'created_at' => $this->iso($r['created_at']), 'days_old' => $days, 'badge' => $days >= self::OVERDUE_DAYS ? 'overdue' : ($days >= self::WARN_DAYS ? 'two_weeks' : 'recent'),
                'notes' => $r['notes'], 'repayments' => $reps[$r['id']] ?? []];
        }
        $out = array_map(fn ($c) => ['id' => $c['id'], 'name' => $c['name'], 'phone' => $c['phone'], 'total_owed' => $c['owed']->toString(), 'oldest_debt_date' => $this->iso($c['oldest']), 'oldest_days' => $c['oldest_days'], 'is_overdue' => $c['oldest_days'] >= self::OVERDUE_DAYS, 'sales' => $c['sales'], '_owed' => $c['owed']->minor], array_values($by));
        usort($out, fn ($a, $b) => $b['_owed'] <=> $a['_owed'] ?: strcmp($a['name'], $b['name']));
        return array_map(function ($c) { unset($c['_owed']); return $c; }, $out);
    }

    // ================================================================================================ statement
    /**
     * Running account of a customer's CREDIT sales: debit = sale total, credits = money paid at the till and later repayments.
     * Closing balance always equals the customer's current debt.
     * @param array<string,mixed> $q @return array<string,mixed>
     */
    public function statement(TenantContext $t, string $customerId, array $q): array
    {
        $t->require('credit.read');
        if (!Uuid::isValid($customerId)) { throw ApiException::notFound(); }
        if ($extra = array_diff(array_keys($q), ['from', 'to'])) { throw ApiException::validation([(string) reset($extra) => ['Unknown filter.']]); }
        $c = $this->customers->customer($t->businessId, $customerId, true) ?? throw ApiException::notFound();
        $tz = new \DateTimeZone($this->sales->businessTimezone($t->businessId));
        $from = $this->day($q, 'from', $tz, 0);
        $to = $this->day($q, 'to', $tz, 1);

        $events = [];
        foreach ($this->sales->creditSalesOf($t->businessId, $customerId) as $s) {
            $events[] = ['at' => $s['created_at'], 'ord' => 0, 'id' => $s['id'], 'type' => 'sale', 'ref' => $s['receipt_number'], 'sale_id' => $s['id'], 'debit' => Money::parse($s['total_amount']), 'credit' => Money::zero(), 'method' => null];
            if (Money::parse($s['amount_paid'])->minor > 0) {
                $events[] = ['at' => $s['created_at'], 'ord' => 1, 'id' => $s['id'], 'type' => 'paid_at_sale', 'ref' => $s['receipt_number'], 'sale_id' => $s['id'], 'debit' => Money::zero(), 'credit' => Money::parse($s['amount_paid']), 'method' => null];
            }
        }
        foreach ($this->sales->repaymentsOfCustomer($t->businessId, $customerId) as $r) {
            $events[] = ['at' => $r['created_at'], 'ord' => 2, 'id' => $r['id'], 'type' => 'repayment', 'ref' => $r['receipt_number'], 'sale_id' => $r['sale_id'], 'debit' => Money::zero(), 'credit' => Money::parse($r['amount']), 'method' => $r['payment_method']];
        }
        usort($events, fn ($a, $b) => [$a['at'], $a['ord'], $a['id']] <=> [$b['at'], $b['ord'], $b['id']]);
        if (count($events) > 5000) { throw new ApiException('too_large', 'This statement is too long; narrow the date range.', 413); }

        $running = Money::zero();
        $opening = Money::zero();
        $lines = [];
        foreach ($events as $e) {
            $before = $from !== null && $e['at'] < $from;
            $after = $to !== null && $e['at'] >= $to;
            $running = $running->add($e['debit'])->sub($e['credit']);
            if ($before) { $opening = $running; continue; }
            if ($after) { continue; }
            $lines[] = ['date' => $this->iso($e['at']), 'type' => $e['type'], 'reference' => $e['ref'], 'sale_id' => $e['sale_id'], 'method' => $e['method'], 'debit' => $e['debit']->toString(), 'credit' => $e['credit']->toString(), 'balance' => $running->toString()];
        }
        $closing = $lines ? Money::parse($lines[count($lines) - 1]['balance']) : $opening;
        return [
            'customer' => ['id' => $c['id'], 'name' => $c['name'], 'phone' => $c['phone']],
            'from' => $q['from'] ?? null, 'to' => $q['to'] ?? null,
            'opening_balance' => $opening->toString(), 'closing_balance' => $closing->toString(), 'lines' => $lines,
            'current_balance' => Money::parse($this->sales->customerBalance($t->businessId, $customerId))->toString(),
        ];
    }

    // ================================================================================================ helpers
    private function iso(string $dt): string { return (new \DateTimeImmutable($dt, new \DateTimeZone('UTC')))->format('Y-m-d\TH:i:s.v\Z'); }

    /** @param array<string,mixed> $q */
    private function uuid(array $q, string $k): ?string
    {
        if (!isset($q[$k])) { return null; }
        if (!is_string($q[$k]) || !Uuid::isValid($q[$k])) { throw ApiException::validation([$k => ['Must be a valid id.']]); }
        return $q[$k];
    }

    /** @param array<string,mixed> $q */
    private function day(array $q, string $k, \DateTimeZone $tz, int $plus): ?string
    {
        if (!isset($q[$k])) { return null; }
        $d = is_string($q[$k]) ? \DateTimeImmutable::createFromFormat('!Y-m-d', $q[$k], $tz) : false;
        if (!$d || $d->format('Y-m-d') !== $q[$k]) { throw ApiException::validation([$k => ['Must be a date as YYYY-MM-DD.']]); }
        return Clock::sql($d->modify("+$plus day")->setTimezone(new \DateTimeZone('UTC')));
    }
}
