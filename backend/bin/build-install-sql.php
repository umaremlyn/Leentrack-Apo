#!/usr/bin/env php
<?php
declare(strict_types=1);

/**
 * Builds ONE SQL file that creates the whole database, for hosts without a terminal (import it in phpMyAdmin).
 * It applies every database/migrations/*.up.sql in order and records each in schema_migrations with the same checksum
 * bin/migrate.php would store, so a later `migrate.php up` sees nothing left to do.
 *   php bin/build-install-sql.php > database/install/leentrack-install.sql
 */
if (PHP_SAPI !== 'cli') { exit(1); }
$dir = dirname(__DIR__) . '/database/migrations';
$files = glob($dir . '/*.up.sql') ?: [];
sort($files);
echo "-- LeenTrack database installer (generated by bin/build-install-sql.php; do not edit).\n";
echo "-- Import into an EMPTY database in phpMyAdmin (Import tab). If imported twice MySQL stops at the first INSERT with 'Duplicate entry 0001': nothing is changed.\n";
echo "SET NAMES utf8mb4;\n\n";
echo "CREATE TABLE IF NOT EXISTS schema_migrations (\n  version VARCHAR(20) NOT NULL PRIMARY KEY,\n  name VARCHAR(190) NOT NULL,\n  checksum CHAR(64) NOT NULL,\n  batch INT NOT NULL,\n  applied_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;\n\n";
foreach ($files as $f) {
    if (!preg_match('/^(\d{4})_([a-z0-9_]+)\.up\.sql$/', basename($f), $m)) { fwrite(STDERR, "bad file name " . basename($f) . "\n"); exit(1); }
    $sql = rtrim((string) file_get_contents($f));
    if (stripos($sql, 'DELIMITER') !== false) { fwrite(STDERR, "{$m[1]} uses DELIMITER: not importable this way\n"); exit(1); }
    echo "-- ---------------------------------------------------------------- {$m[1]} {$m[2]}\n";
    echo $sql . (str_ends_with($sql, ';') ? '' : ';') . "\n";
    echo "INSERT INTO schema_migrations (version, name, checksum, batch) VALUES ('{$m[1]}', '{$m[2]}', '" . hash_file('sha256', $f) . "', 1);\n\n";
}
echo "-- done: " . count($files) . " migrations\n";
